#### Write Table 1 in the paper's layout as a LaTeX fragment ####
# run from sim1_repro/:  Rscript scripts/table1_paper_tex.R <tag>
# writes results/table1_<tag>_paper.tex; needs bm and amsmath in the paper's preamble

source("R/load.R")

args <- commandArgs(trailingOnly = TRUE)
tag <- if (length(args) >= 1) args[1] else "full_v2"

summ <- function(b, se, beta) {
  c(bias = 100 * (mean(b) - beta) / beta, se = mean(se), sd = sd(b),
    cov = 100 * mean(abs(b - beta) <= qnorm(0.975) * se))
}
tab <- lapply(CELLS$cell, function(k) {
  d <- readRDS(file.path(PROJ, "results", tag, sprintf("cell%02d.rds", k)))
  n1 <- if ("n1" %in% names(d)) d$n1[1] else N_MAIN
  n2 <- if ("n2" %in% names(d)) d$n2[1] else N_VAL_SUBJ
  B <- nrow(d); all_b <- d$b_rrc; beta <- d$beta[1]; n_out <- sum(!(d$conv %in% TRUE))
  out_mean <- mean(d$b_rrc[!(d$conv %in% TRUE)])
  d <- d[d$conv %in% TRUE, ]
  list(k = k, n1 = n1, n2 = n2, B = B, n_out = n_out, out_mean = out_mean, naive = summ(d$b_naive, d$se_naive, beta), rrc = summ(d$b_rrc, d$se_rrc, beta),
       bias_all = 100 * (mean(all_b) - beta) / beta)
})

num <- function(v, d) gsub("-", "$-$", sprintf(paste0("%.", d, "f"), v), fixed = TRUE)
mark <- function(l) sprintf("\\textsuperscript{\\textit{%s}}", l)
gen <- c(ind = "\\text{ind}", ar1 = "\\text{AR(1)}", dex = "\\text{DEX}")

row1 <- function(t) {
  cl <- CELLS[CELLS$cell == t$k, ]
  dist <- if (cl$error == "add") "MVN" else "Log-MVN"
  lab <- sprintf("%s($\\bm{\\mu_C},\\bm{\\Sigma}_{%s}$)", dist, gen[[cl$cor]])
  if (t$n_out > 0) lab <- paste0(lab, mark("d"))
  paste0(paste(c(lab, num(t$naive[["bias"]], 2), num(t$rrc[["bias"]], 2), num(t$naive[["se"]], 3), num(t$rrc[["se"]], 3),
                 num(t$naive[["sd"]], 3), num(t$rrc[["sd"]], 3), num(t$naive[["cov"]], 2), num(t$rrc[["cov"]], 2)),
               collapse = " & "), " \\\\")
}
blk <- function(lab, txt, ks) c("\\multicolumn{9}{|c|}{}\\\\", "\\hline",
  sprintf("\\bf %s & \\multicolumn{8}{c|}{%s} \\\\", lab, txt), "\\hline",
  unlist(lapply(tab[ks], function(t) c(row1(t), "\\hline"))))

ex <- Filter(function(t) t$n_out > 0, tab)
note_d <- sprintf(
  "Excludes replications in which a fit did not converge or ended on the boundary of the parameter space: %s of 2,000 in the rows marked, in order.",
  paste(sapply(ex, function(t) t$n_out), collapse = ", "))

# cells may differ in size (full_v4); one sentence when they all agree, one per model otherwise
size_txt <- function(ks) {
  t <- tab[[ks[1]]]
  sprintf("main study sample size $n_1$=%d, validation study sample size $n_2$=%d, simulation repetition number $B$=%d", t$n1, t$n2, t$B)
}
same <- function(ks) nrow(unique(do.call(rbind, lapply(tab[ks], function(t) c(t$n1, t$n2, t$B))))) == 1
note_size <- if (same(1:12)) {
  sprintf("Main study sample size $n_1$=%d, validation study sample size $n_2$=%d, study duration $T^{*}$=55, simulation repetition number $B$=%d, cumulative incidence rate about 10\\%%.",
          tab[[1]]$n1, tab[[1]]$n2, tab[[1]]$B)
} else {
  stopifnot(same(1:6), same(7:12))
  sprintf("Cox rows: %s. ERR rows: %s. Study duration $T^{*}$=55, cumulative incidence rate about 10\\%%.", size_txt(1:6), size_txt(7:12))
}

lines <- c(
"% Simulation 1 results; generated by scripts/table1_paper_tex.R",
"% preamble needs: bm, amsmath (for \\text)",
"\\begin{table}[!htbp]", "\\small", "\\centering",
"\\caption{Summary Results of Simulation Study of Naive VS RRC-Corrected Effect Estimates of Cumulative Total Exposure}",
"\\begin{minipage}{\\textwidth}", "\\centering",
"\\setlength{\\tabcolsep}{3pt}",
"\\begin{tabular}{|c|c|c|c|c|c|c|c|c|}", "\\hline",
sprintf("\\bf Generation of $C$ & \\multicolumn{2}{|c|}{\\shortstack{\\bf Relative\\\\\\bf bias ($\\%%$)%s}} & \\multicolumn{2}{|c|}{\\shortstack{\\bf Average\\\\\\bf estimated SD%s}} & \\multicolumn{2}{|c|}{\\shortstack{\\bf Monte-Carlo\\\\\\bf SD%s}} & \\multicolumn{2}{|c|}{\\shortstack{\\bf 95$\\%%$ CI\\\\\\bf coverage}}\\\\",
        mark("a"), mark("b"), mark("c")),
"\\hline", " & Naive & RRC & Naive & RRC & Naive & RRC & Naive & RRC \\\\", "\\hline",
blk("Cox+Additive", "Cox true $\\beta=\\log(1.5)\\approx 0.405$, additive independent measurement error", 1:3),
blk("Cox+Multiplicative", "Cox true $\\beta=\\log(1.5)\\approx 0.405$, multiplicative independent measurement error", 4:6),
blk("ERR+Additive", "ERR true $\\beta\\approx 0.423$, additive independent measurement error", 7:9),
blk("ERR+Multiplicative", "ERR true $\\beta\\approx 0.423$, multiplicative independent measurement error", 10:12),
"\\end{tabular}", "\\par", "{\\raggedright\\footnotesize",
"\\begin{list}{}{\\setlength{\\leftmargin}{1.2em}\\setlength{\\labelwidth}{0.8em}\\setlength{\\labelsep}{0.4em}%",
"  \\setlength{\\itemsep}{0pt}\\setlength{\\parsep}{0pt}\\setlength{\\topsep}{4pt}\\setlength{\\partopsep}{0pt}}",
paste0("\\item[", mark("a"), "] $100\\times\\{\\text{mean}(\\hat{\\beta})-\\beta\\}/\\beta$."),
paste0("\\item[", mark("b"), "] Mean of the estimated standard errors: model-based for Naive, sandwich estimator for RRC."),
paste0("\\item[", mark("c"), "] Empirical standard deviation of $\\hat{\\beta}$ across replications."),
if (length(ex) > 0) paste0("\\item[", mark("d"), "] ", note_d),
paste0("\\item[] ", note_size, " Parameter values are in Tables \\ref{tab:sim1_settings_common} and \\ref{tab:sim1_settings_cell}."),
"\\end{list}", "\\par}", "\\end{minipage}", "\\label{tab:sim1}", "\\end{table}")
out <- file.path(PROJ, "results", sprintf("table1_%s_paper.tex", tag))
writeLines(lines, out)
cat("wrote", out, "\n")
